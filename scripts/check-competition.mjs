import assert from 'node:assert/strict';
import {defaultCompetition,competitionState,riyadhInstant,riyadhLocal,countdownParts,parseCompetition} from '../lib/competition.ts';
const requested='2026-10-14T13:00:00.000Z',end=Date.parse(requested);
assert.equal(riyadhInstant('2026-10-14T16:00'),requested);
assert.equal(riyadhLocal(requested),'2026-10-14T16:00');
assert.equal(riyadhLocal('2026-10-14T22:00:00.000Z'),'2026-10-15T01:00');
for(const date of ['2026-02-30T16:00','2026-10-14T24:00','2026-13-14T16:00','2026-10-14',''])assert.throws(()=>riyadhInstant(date));
const event=defaultCompetition('chores-grade-4');
assert.equal(event.endsAt,requested);
assert.equal(defaultCompetition('life-stories').enabled,false);
assert.equal(competitionState(event,end-1).ended,false);
assert.equal(competitionState(event,end).ended,true);
assert.equal(competitionState({...event,enabled:false},end+1000).ended,false);
assert.deepEqual(countdownParts(requested,end-((2*86400+3*3600+4*60+5)*1000)),{days:2,hours:3,minutes:4,seconds:5});
assert.deepEqual(countdownParts(requested,end+5000),{days:0,hours:0,minutes:0,seconds:0});
const b={enabled:true,showCountdown:true,mode:'days',days:3,hours:0,minutes:0,prize:'جائزة للمركز الأول'};
assert.equal(parseCompetition(b,end).endsAt,'2026-10-17T13:00:00.000Z');
assert.equal(parseCompetition({...b,days:0,hours:0,minutes:1},end).endsAt,'2026-10-14T13:01:00.000Z');
for(const change of [{days:-1},{days:0.5},{days:null},{days:'3'},{days:3651},{hours:24},{minutes:60},{days:0,hours:0,minutes:0},{enabled:'true'},{showCountdown:1},{mode:'date',endsAt:requested},{mode:'date',endsAt:'2026-02-30T13:00:00.000Z'}])assert.throws(()=>parseCompetition({...b,...change},end));
assert.equal(parseCompetition({...b,mode:'date',endsAt:'2026-10-15T13:00:00.000Z'},end).endsAt,'2026-10-15T13:00:00.000Z');
assert.equal(parseCompetition({...b,enabled:false},end).endsAt,null);
console.log('PASS: Saudi date conversion across midnight, invalid dates, exact deadline, nonnegative countdown units and persistent server-anchored duration.');
